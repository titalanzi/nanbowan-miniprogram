Page({
  data: {
    type: 'service',
    docTitle: '用户服务协议',
    effectiveDate: '2026年9月16日',
    intro: SERVICE_INTRO,
    sections: SERVICE_SECTIONS
  },

  onLoad: function (options) {
    const type = (options && options.type === 'privacy') ? 'privacy' : 'service'
    const isPrivacy = type === 'privacy'
    const docTitle = isPrivacy ? '隐私政策' : '用户服务协议'

    this.setData({
      type,
      docTitle,
      intro: isPrivacy ? PRIVACY_INTRO : SERVICE_INTRO,
      sections: isPrivacy ? PRIVACY_SECTIONS : SERVICE_SECTIONS
    })

    wx.setNavigationBarTitle({ title: docTitle })
  },

  // 打开微信官方的《小程序用户隐私保护指引》
  openWxPrivacy: function () {
    if (wx.openPrivacyContract) {
      wx.openPrivacyContract({
        fail: () => {
          wx.showToast({ title: '暂未配置隐私保护指引', icon: 'none' })
        }
      })
    } else {
      wx.showToast({ title: '当前微信版本不支持查看', icon: 'none' })
    }
  }
})
